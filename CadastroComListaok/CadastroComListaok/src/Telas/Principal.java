     private void iniciarTabela(){
        if (tableModel == null) {
        // Só cria o modelo na primeira vez
        tableModel = new DefaultTableModel(
            new Object[]{"Nome", "Idade", "Cadastro Finalizado", "Observação"}, 0
        );
        jTable1.setModel(tableModel);
    }

    // Limpa as linhas antes de recarregar
    tableModel.setRowCount(0);

    // Recarrega os dados da lista
    for (Pessoa p : listaPessoas.getPessoas()) {
        tableModel.addRow(new Object[]{
            p.getNome(),
            p.getIdade(),
            p.isCadastroFinalizado() ? "Sim" : "Não",
            p.getObservacao()
        });
    }
    }
     
      public void geraAcessbilidade() {

            //DEFINE MÉTODO QUE ASSOCIA TECLA DE ATALHO "ATL + D" PARA O BOTÃO
            btnAdicionar.setMnemonic(KeyEvent.VK_D);
        }
     
      public void atualizarPessoa(int index, Pessoa pessoa) {
    listaPessoas.getPessoas().set(index, pessoa);
    iniciarTabela(); // Atualiza a tabela
}
