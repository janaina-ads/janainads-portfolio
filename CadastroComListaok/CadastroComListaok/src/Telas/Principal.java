    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
            String nome = txtNome.getText();
    int idade = Integer.parseInt(txtIdade.getText());
    String observacao = txtObservacao.getText();

    Pessoa pessoa = new Pessoa(nome, idade, observacao);

    listaPessoas.adicionarPessoa(pessoa);

    iniciarTabela(); // Atualiza a tabela

    txtNome.setText("");
    txtIdade.setText("");
    txtObservacao.setText("");
        
    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarActionPerformed
      int selectedRow = jTable1.getSelectedRow();
    if (selectedRow != -1) {
        listaPessoas.removerPessoa(selectedRow);
        iniciarTabela(); // Atualiza a tabela
    } else {
        JOptionPane.showMessageDialog(this, "Selecione uma pessoa na tabela para remover.");
    }

    }//GEN-LAST:event_btnDeletarActionPerformed

